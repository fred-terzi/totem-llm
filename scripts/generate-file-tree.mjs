#!/usr/bin/env node
/**
 * generate-file-tree.mjs
 *
 * Generates a clean, filtered file tree of the repository.
 *
 * Usage:
 *   node scripts/generate-file-tree.mjs            # print to stdout
 *   node scripts/generate-file-tree.mjs --file     # write to FILE_TREE.md
 *   node scripts/generate-file-tree.mjs --json     # output as JSON
 *
 * Excluded paths (not part of source):
 *   node_modules, .git, dist, embed, coverage,
 *   storage, logs, images, locales, browser-extension,
 *   totem_project_management, lockfiles
 */

import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// ── Exclusion rules ──────────────────────────────────────────────
const EXCLUDED_DIRS = new Set([
  "node_modules",
  ".git",
  "dist",
  "embed",
  "coverage",
  "storage",
  "logs",
  "images",
  "locales",
  "browser-extension",
  "totem_project_management",
  "__pycache__",
  "totem_docs",        // optional – remove from this set to include
  "cloud-deployments", // optional – remove from this set to include
]);

const EXCLUDED_FILES = new Set([
  "yarn.lock",
  "package-lock.json",
]);

// ── Tree builder ──────────────────────────────────────────────────
/**
 * Recursively build a nested tree object.
 * Returns { [name]: { type: "dir"|"file", children?: {...} } }
 */
function buildTree(dir, prefix = "") {
  const entries = readdirSync(dir, { withFileTypes: true });
  const tree = {};

  for (const entry of entries) {
    if (entry.name.startsWith(".") && entry.name !== ".devcontainer") continue;
    if (EXCLUDED_DIRS.has(entry.name)) continue;
    if (EXCLUDED_FILES.has(entry.name)) continue;

    const fullPath = join(dir, entry.name);
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;

    if (entry.isDirectory()) {
      tree[entry.name] = { type: "dir", children: buildTree(fullPath, rel) };
    } else if (entry.isFile()) {
      tree[entry.name] = { type: "file" };
    }
  }

  return tree;
}

// ── Renderers ─────────────────────────────────────────────────────

/** Flat list: "path/to/file" per line */
function renderFlat(tree, prefix = "") {
  const lines = [];
  for (const [name, node] of Object.entries(tree)) {
    const rel = prefix ? `${prefix}/${name}` : name;
    if (node.type === "dir") {
      lines.push(`${rel}/`);
      lines.push(...renderFlat(node.children, rel));
    } else {
      lines.push(rel);
    }
  }
  return lines;
}

/** Pretty tree with └─ / ├─ connectors */
function renderTree(tree, prefix = "", isLast = true) {
  const lines = [];
  const names = Object.keys(tree);
  const len = names.length;

  names.forEach((name, i) => {
    const last = i === len - 1;
    const connector = last ? "└── " : "├── ";
    const node = tree[name];
    const rel = prefix ? `${prefix}/${name}` : name;

    if (node.type === "dir") {
      lines.push(`${prefix}${connector}${name}/`);
      const childPrefix = prefix + (last ? "    " : "│   ");
      lines.push(...renderTree(node.children, childPrefix));
    } else {
      lines.push(`${prefix}${connector}${name}`);
    }
  });

  return lines;
}

/** JSON output */
function renderJson(tree) {
  return JSON.stringify(tree, null, 2);
}

// ── Main ──────────────────────────────────────────────────────────
const args = process.argv.slice(2);

const tree = buildTree(ROOT);
const flat = renderFlat(tree);
const pretty = renderTree(tree);
const fileCount = flat.filter((l) => !l.endsWith("/")).length;
const dirCount = flat.filter((l) => l.endsWith("/")).length;

const timestamp = new Date().toISOString().replace("T", " ").replace(/\.\d+Z/, " UTC");

if (args.includes("--json")) {
  console.log(renderJson(tree));
} else if (args.includes("--file")) {
  const outPath = join(ROOT, "FILE_TREE.md");
  const header = [
    `# File Tree`,
    ``,
    `<!-- Auto-generated by \`node scripts/generate-file-tree.mjs --file\` -->`,
    `<!-- Generated: ${timestamp} -->`,
    `<!-- ${fileCount} files, ${dirCount} directories -->`,
    ``,
    "```",
  ].join("\n");

  const footer = "\n```\n";
  writeFileSync(outPath, header + "\n" + pretty.join("\n") + footer, "utf-8");
  console.log(`✓ Wrote FILE_TREE.md  (${fileCount} files, ${dirCount} dirs)`);
} else {
  // default: print pretty tree to stdout
  console.log(pretty.join("\n"));
  console.error(`\n— ${fileCount} files, ${dirCount} directories —`);
}
